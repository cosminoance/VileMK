"""Write web/src/lib/zmkcodes.ts from ZMK's dt-bindings headers.

The Studio page gets bindings as numbers; this table turns them back into the
names a keymap would use. Run it against the ZMK checkout in `.zmk/zmk` (or any
ZMK source) when ZMK adds keycodes; the page reads only the committed output.

    python3 -m vilemk.zmkcodes [ZMK_DIR]
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "web/src/lib/zmkcodes.ts"
DEFINE = re.compile(r"^#define\s+(\w+)(\([^)]*\))?\s+(.+?)\s*(?://.*)?$", re.M)
MODS = {"LC": 0x01, "LS": 0x02, "LA": 0x04, "LG": 0x08,
        "RC": 0x10, "RS": 0x20, "RA": 0x40, "RG": 0x80}
# Behaviors whose first parameter is a command constant, by header.
COMMANDS = {"bt": "bt.h", "out": "outputs.h", "rgb_ug": "rgb.h",
            "bl": "backlight.h", "ext_power": "ext_power.h"}


def defines(path: Path) -> dict:
    """Object-like defines only, `NAME -> text`."""
    return {m[1]: m[3] for m in
            DEFINE.finditer(re.sub(r"\\\n\s*", " ", path.read_text())) if not m[2]}


def keycodes(inc: Path) -> dict:
    """`usage -> [names]` for every keycode keys.h defines, modifier bits included."""
    raw = {**defines(inc / "hid_usage_pages.h"), **defines(inc / "hid_usage.h")}
    keys = defines(inc / "keys.h")
    raw.update(keys)
    env = {"ZMK_HID_USAGE": lambda p, i: (p << 16) | i,
           **{m: (lambda bit: lambda k: (bit << 24) | k)(b) for m, b in MODS.items()}}
    cache: dict = {}

    def value(name: str) -> int:
        if name not in cache:
            expr = re.sub(r"\b[A-Za-z_]\w*\b",
                          lambda m: m[0] if m[0] in env else f"V({m[0]!r})", raw[name])
            cache[name] = eval(expr, {"V": value, **env})
        return cache[name]

    out: dict = {}
    for name in keys:
        try:
            out.setdefault(value(name), []).append(name)
        except (KeyError, SyntaxError, TypeError):
            pass
    return out


def commands(inc: Path) -> dict:
    """`head -> {number: [name, takes_arg]}` from the `*_CMD` constants."""
    out = {}
    for head, header in COMMANDS.items():
        d = defines(inc / header)
        table = {}
        for name, text in d.items():
            if name.endswith("_CMD") and text.isdigit():
                short = name[:-4]
                alias = next((k for k, v in d.items() if v == name), None)
                if short not in d and alias:
                    # ext_power.h names its commands EP_* and they take no argument.
                    table[int(text)] = [alias, False]
                    continue
                takes = not (short in d and d[short].endswith(" 0"))
                table[int(text)] = [short, takes]
        # outputs.h names its values directly.
        for name, text in d.items():
            if head == "out" and text.isdigit():
                table[int(text)] = [name, False]
        out[head] = table
    return out


def heads(zmk: Path) -> dict:
    """`display-name -> node label` for ZMK's own behaviors."""
    node = re.compile(r"(\w+):\s*[\w,-]+\s*\{[^{}]*?display-name\s*=\s*\"([^\"]+)\"")
    out = {}
    for f in sorted((zmk / "app/dts/behaviors").glob("*.dtsi")):
        for label, name in node.findall(f.read_text()):
            out[name] = label
    return out


def main(argv: list) -> int:
    zmk = Path(argv[0]) if argv else ROOT / ".zmk/zmk"
    inc = zmk / "app/include/dt-bindings/zmk"
    if not (inc / "keys.h").exists():
        print(f"no ZMK headers under {inc}", file=sys.stderr)
        return 1
    codes = keycodes(inc)
    OUT.write_text(
        "// Generated by `python3 -m vilemk.zmkcodes` from ZMK's dt-bindings headers.\n"
        "// Do not edit; run it again when ZMK adds keycodes.\n\n"
        "/** HID usage (modifier bits in the top byte) -> every ZMK name for it. */\n"
        "export const USAGES: Record<number, string[]> = "
        + json.dumps({k: codes[k] for k in sorted(codes)}, separators=(",", ":")) + ";\n\n"
        "/** Behavior head -> command number -> [name, takes a second parameter]. */\n"
        "export const COMMANDS: Record<string, Record<number, [string, boolean]>> = "
        + json.dumps(commands(inc), separators=(",", ":")) + ";\n\n"
        "/** A behavior's Studio display name -> its keymap label. */\n"
        "export const HEADS: Record<string, string> = "
        + json.dumps(heads(zmk), separators=(",", ":")) + ";\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(codes)} usages")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
